public enum PlaygroundLanguage: String, CaseIterable, Codable, Sendable {
    case english = "en"
    case simplifiedChinese = "zh-Hans"

    public var displayName: String { self == .english ? "English" : "简体中文" }
    public var locale: Locale { Locale(identifier: rawValue) }

    public static func resolve(saved: String?, preferredLanguages: [String]) -> Self {
        if let saved, let value = Self(rawValue: saved) { return value }
        return preferredLanguages.first?.lowercased().hasPrefix("zh") == true ? .simplifiedChinese : .english
    }

    public func text(_ key: String) -> String {
        self == .english ? key : Self.chinese[key] ?? key
    }

    public func format(_ key: String, _ arguments: CVarArg...) -> String {
        String(format: text(key), locale: locale, arguments: arguments)
    }

